CREATE TABLE IF NOT EXISTS shifts (
    id BINARY(16) NOT NULL,
    created_at BIGINT NULL,
    updated_at BIGINT NULL,
    deleted_at BIGINT NULL,
    created_by VARCHAR(255) NULL,
    updated_by VARCHAR(255) NULL,
    deleted_by VARCHAR(255) NULL,
    is_deleted BIT NULL,
    shift_name VARCHAR(255) NOT NULL,
    start_time VARCHAR(255) NOT NULL,
    end_time VARCHAR(255) NOT NULL,
    tenant_id BINARY(16) NOT NULL,
    organisation_id BINARY(16) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_shift_tenant_deleted (tenant_id, is_deleted),
    KEY idx_shift_organisation_deleted (organisation_id, is_deleted),
    CONSTRAINT fk_shift_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_shift_organisation FOREIGN KEY (organisation_id) REFERENCES tenants (id)
);

CREATE TABLE IF NOT EXISTS transport_requests (
    id BINARY(16) NOT NULL,
    created_at BIGINT NULL,
    updated_at BIGINT NULL,
    deleted_at BIGINT NULL,
    created_by VARCHAR(255) NULL,
    updated_by VARCHAR(255) NULL,
    deleted_by VARCHAR(255) NULL,
    is_deleted BIT NULL,
    tenant_id BINARY(16) NOT NULL,
    organisation_id BINARY(16) NULL,
    shift_id BINARY(16) NULL,
    requested_by_user_id BINARY(16) NULL,
    passenger_id BINARY(16) NULL,
    passenger_type VARCHAR(255) NULL,
    passenger_name VARCHAR(255) NULL,
    passenger_email VARCHAR(255) NULL,
    passenger_phone VARCHAR(255) NULL,
    trip_type VARCHAR(255) NOT NULL,
    start_date BIGINT NOT NULL,
    end_date BIGINT NULL,
    recurrence_frequency VARCHAR(255) NULL,
    recurrence_interval INT NULL,
    days_of_week VARCHAR(255) NULL,
    pickup_address VARCHAR(255) NOT NULL,
    pickup_latitude DECIMAL(10,7) NOT NULL,
    pickup_longitude DECIMAL(10,7) NOT NULL,
    dropoff_address VARCHAR(255) NOT NULL,
    dropoff_latitude DECIMAL(10,7) NOT NULL,
    dropoff_longitude DECIMAL(10,7) NOT NULL,
    request_status VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_transport_request_tenant_dates (tenant_id, start_date, end_date),
    KEY idx_transport_request_organisation_dates (organisation_id, start_date, end_date),
    KEY idx_transport_request_shift (shift_id),
    KEY idx_transport_request_passenger (passenger_id),
    CONSTRAINT fk_transport_request_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
    CONSTRAINT fk_transport_request_organisation FOREIGN KEY (organisation_id) REFERENCES tenants (id),
    CONSTRAINT fk_transport_request_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
    CONSTRAINT fk_transport_request_user FOREIGN KEY (requested_by_user_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_transport_request_passenger FOREIGN KEY (passenger_id) REFERENCES people_tenant (id)
);
