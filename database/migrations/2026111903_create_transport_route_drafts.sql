CREATE TABLE IF NOT EXISTS transport_route_drafts (
  id BINARY(16) NOT NULL PRIMARY KEY,
  tenant_id BINARY(16) NOT NULL,
  organisation_id BINARY(16) NOT NULL,
  shift_id BINARY(16) NOT NULL,
  route_direction VARCHAR(32) NOT NULL,
  vehicle_type_id BINARY(16) NULL,
  allowed_passenger INT NOT NULL,
  direction_text VARCHAR(1000) NOT NULL,
  pickup_address VARCHAR(500) NOT NULL,
  dropoff_address VARCHAR(500) NOT NULL,
  requests_json JSON NOT NULL,
  draft_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  expires_at BIGINT NOT NULL,
  created_at BIGINT NULL,
  updated_at BIGINT NULL,
  deleted_at BIGINT NULL,
  created_by VARCHAR(255) NULL,
  updated_by VARCHAR(255) NULL,
  deleted_by VARCHAR(255) NULL,
  is_deleted BIT(1) NULL DEFAULT b'0',
  CONSTRAINT fk_transport_route_drafts_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
  CONSTRAINT fk_transport_route_drafts_organisation FOREIGN KEY (organisation_id) REFERENCES tenants(id),
  CONSTRAINT fk_transport_route_drafts_shift FOREIGN KEY (shift_id) REFERENCES shifts(id),
  CONSTRAINT fk_transport_route_drafts_vehicle_type FOREIGN KEY (vehicle_type_id) REFERENCES vehicle_types(id),
  INDEX idx_route_drafts_tenant_status_expiry (tenant_id, draft_status, expires_at),
  INDEX idx_route_drafts_expiry_status (expires_at, draft_status)
) ENGINE=InnoDB;
